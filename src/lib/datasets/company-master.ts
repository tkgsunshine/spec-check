function toKatakana(str: string): string {
  return str.replace(/[\u3041-\u3096]/g, m => String.fromCharCode(m.charCodeAt(0) + 0x60));
}
function toHiragana(str: string): string {
  return str.replace(/[\u30a1-\u30f6]/g, m => String.fromCharCode(m.charCodeAt(0) - 0x60));
}

/**
 * 会社検索API / オートコンプリート用のフィルタリング関数
 * ひらがな・カタカナ・英大文字小文字・証券コード・通称エイリアスすべての「部分一致」を全企業に共通適用します。
 */
export function searchCompanies(query: string, maxResults = 12): CompanyMasterItem[] {
  if (!query || query.trim() === '') return [];
  const rawQ = query.trim().toLowerCase();
  const qKata = toKatakana(rawQ);
  const qHira = toHiragana(rawQ);

  const results = COMPANY_MASTER.filter(c => {
    const checkString = (target: string) => {
      const t = target.toLowerCase();
      return t.includes(rawQ) || t.includes(qKata) || t.includes(qHira);
    };

    const nameMatch = checkString(c.name);
    const stockCodeMatch = c.stockCode ? c.stockCode.includes(rawQ) : false;
    const aliasMatch = c.aliases.some(alias => checkString(alias));
    const industryMatch = checkString(c.industry);
    return nameMatch || stockCodeMatch || aliasMatch || industryMatch;
  });

  // もしマスタ直接検索で引っかからない場合や入力中のアシストとして、自由入力企業候補を安全に付与
  const isExactMasterMatch = results.some(r => r.name.toLowerCase() === rawQ || r.aliases.some(a => a.toLowerCase() === rawQ));
  if (!isExactMasterMatch && rawQ.length >= 2) {
    const isOracleLike = rawQ.includes('オラクル') || rawQ.includes('oracle');
    const isSalesforceLike = rawQ.includes('セールスフォース') || rawQ.includes('salesforce');
    const isBigTech = isOracleLike || isSalesforceLike || rawQ.includes('sap') || rawQ.includes('cisco');

    const dynamicFallback: CompanyMasterItem = {
      id: `dynamic_${Date.now()}`,
      name: query.trim(),
      aliases: [query.trim()],
      marketCategory: isBigTech ? 'GLOBAL_TOP' : 'PRIME',
      marketCategoryLabel: isBigTech ? '外資トップ・グローバル大手' : '上場企業・一般企業区分',
      averageAnnualSalary: isBigTech ? 1200 : 850,
      industry: '一般企業 / 業界指定なし',
      baseScore: isBigTech ? 92 : 82,
    };

    // マスタ結果の末尾または先頭に提示
    return [...results.slice(0, maxResults - 1), dynamicFallback];
  }

  return results.slice(0, maxResults);
}
